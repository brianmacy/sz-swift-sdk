#!/usr/bin/env bash
# Writes senzing.pc for an installed Senzing runtime, so SwiftPM finds its C
# headers and libSz through pkg-config (no unsafe build flags).
#
# Usage: tools/senzing-pkgconfig.sh [<runtime er directory>] [<output directory>]
#
# The runtime defaults to $SENZING_DIR, then the Homebrew cask locations, then
# /opt/senzing/er. The output directory defaults to a directory SwiftPM always
# searches: $(brew --prefix)/lib/pkgconfig on macOS, /usr/local/lib/pkgconfig
# on Linux (which may need sudo). To write it elsewhere, point PKG_CONFIG_PATH
# at that directory when building.
set -euo pipefail

er="${1:-${SENZING_DIR:-}}"
if [ -z "$er" ]; then
    for candidate in /opt/homebrew/opt/senzing/er /usr/local/opt/senzing/er /opt/senzing/er; do
        if [ -f "$candidate/sdk/c/libSz.h" ]; then
            er="$candidate"
            break
        fi
    done
fi
if [ -z "$er" ] || [ ! -f "$er/sdk/c/libSz.h" ]; then
    echo "No Senzing runtime found: pass its er directory or set SENZING_DIR." >&2
    exit 1
fi

if [ $# -ge 2 ]; then
    out="$2"
elif [ "$(uname -s)" = "Darwin" ]; then
    out="$(brew --prefix)/lib/pkgconfig"
else
    out="/usr/local/lib/pkgconfig"
fi

version="$(sed -n 's/^ *"VERSION": *"\([^"]*\)".*/\1/p' "$er/szBuildVersion.json" | head -1)"
mkdir -p "$out"
cat > "$out/senzing.pc" <<PC
# Generated by sz-swift-sdk tools/senzing-pkgconfig.sh for $er
libdir=$er/lib
includedir=$er/sdk/c

Name: senzing
Description: Senzing SDK runtime (C API and libSz)
Version: ${version:-0}
Cflags: -I\${includedir}
Libs: -L\${libdir} -lSz
PC
echo "Wrote $out/senzing.pc for $er (Senzing ${version:-unknown})"
